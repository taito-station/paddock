//! results の行が足りないレースに、足りない馬番の行だけを INSERT して補う（#742）。
//!
//! 既存の書き込み口はどれも使えない: `paddock-fetch-results` は UPDATE 専用（ADR 0015）、
//! `upsert_results` は既存行を上書きし、`ResultsInteractor::refresh` は着順が 1 行でもあるレースを飛ばす。
//! ここでは**既存行には一切触れず**（DELETE も UPDATE もしない）、無い馬番の行だけを入れる。
//!
//! - `fetch`: 結果ページの HTML をリポジトリの外に保存する（再送しない・失敗で即停止・取得済みは飛ばす）。
//! - `plan`: 出馬表・既存行・結果ページを照合し、入れる行を決める（純関数）。
//! - `apply`: 保存した HTML から DB に書く（ネットワーク不使用・照合に失敗したレースは書かない）。
//!
//! 対象一覧の読み込み・取得間隔の下限・出力先の検査は `fetch-final-odds`（#721）の lib を再利用する（ペーシングの正本を 1 つに
//! 保つため・決定ログ #742）。取得ループ（スキップ・即停止・一時ファイル経由の保存）は同じ形を #742 用に書いている
//! （確定オッズの「非確定が続いたら止める」判定が結果ページには無いため）。停止条件やペーシングを変えるときは両方を見る。

